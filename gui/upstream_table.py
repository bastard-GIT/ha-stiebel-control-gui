"""Elster signal table for one heat pump model, generated from the pinned upstream sources.

Inputs (read only; verify_pin() checks them against upstream/PIN.json):
  upstream/ha-stiebel-control/elster/ElsterTable.h  table rows, ElsterTypeStr, ErrorList, BetriebsartList
  upstream/ha-stiebel-control/model_profile.h        HA_MODEL_ID_* numbers, HA_CONTROLLER_* switches
  upstream/ha-stiebel-control/can_members.h          CanMembers[]
Output: a dict in the format of tests/data/ElsterTable.test.json (format_version 2).

Upstream references (commit 4ec5b3c8ee2dedda328efeec227694280e3f719e, esphome/ha-stiebel-control/):
  elster/KElsterTable.cpp, BuildIndexOrder() lines 201-215, comment "the first row wins" at
      line 206: of several rows with the same index the first one is kept, later ones are dropped.
  can_io.h, generate_read_id() line 65 and generate_write_id() line 71 (CAN ID bytes).

Preprocessor subset (anything else raises UpstreamTableError with file and line):
  #if, #ifdef, #ifndef, #elif, #else, #endif
  expressions: defined(X), defined X, !, &&, ||, ( ), == and !=, integer literals, and macros
  that have an integer value. Directives #include, #pragma and #error are ignored outside the
  table; #define and #undef are applied only for model_profile.h (apply_defines=True).
"""
