def _int(text: str) -> int:
    if text[:2].lower() == "0x":
        return int(text, 16)
    return int(text, 10)


def strip_comments(text: str) -> list[str]:
    """Return the lines of text with // and /* */ comments blanked out.

    String and character literals are kept intact. Line count is preserved, so line
    numbers of the result match the original file.
    """
    out: list[str] = []
    state = "code"  # "code", "line", "block", or the quote character of a literal
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if state == "code":
            if text.startswith("//", i):
                state = "line"
                out.append("  ")
                i += 2
            elif text.startswith("/*", i):
                state = "block"
                out.append("  ")
                i += 2
            elif c in ('"', "'"):
                state = c
                out.append(c)
                i += 1
            else:
                out.append(c)
                i += 1
        elif state == "line":
            if c == "\n":
                state = "code"
                out.append("\n")
            else:
                out.append(" ")
            i += 1
        elif state == "block":
            if text.startswith("*/", i):
                state = "code"
                out.append("  ")
                i += 2
            else:
                out.append("\n" if c == "\n" else " ")
                i += 1
        else:  # inside a string or character literal
            if c == "\n":
                state = "code"
                out.append(c)
                i += 1
            elif c == "\\" and i + 1 < n and text[i + 1] != "\n":
                out.append(text[i:i + 2])
                i += 2
            else:
                if c == state:
                    state = "code"
                out.append(c)
                i += 1
    return "".join(out).split("\n")


def _source_lines(rel: str) -> list[str]:
    path = SOURCE_DIR / rel
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise UpstreamTableError(f"cannot read upstream file {rel}: {exc}") from exc
    return strip_comments(text)


def _load_pin() -> dict:
    try:
        pin = json.loads(PIN_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise UpstreamTableError(f"cannot read pin file {PIN_PATH.name}: {exc}") from exc
    if not isinstance(pin, dict):
        raise UpstreamTableError(f"pin file {PIN_PATH.name} is not a JSON object")
    return pin


def pin_info() -> dict:
    """Return repo, commit and date of the pinned upstream snapshot (upstream/PIN.json)."""
    pin = _load_pin()
    try:
        return {"repo": pin["repo"], "commit": pin["commit"], "date": pin["date"]}
    except KeyError as exc:
        raise UpstreamTableError(f"pin file {PIN_PATH.name} lacks key {exc}") from exc


def verify_pin() -> None:
    """Check the SHA256 of every pinned file. Raises UpstreamTableError on any mismatch."""
    pin = _load_pin()
    files = pin.get("files")
    if not isinstance(files, dict) or not files:
        raise UpstreamTableError(f"pin file {PIN_PATH.name} lists no files")
    missing_from_pin = [f for f in REQUIRED_FILES if f not in files]
    if missing_from_pin:
        raise UpstreamTableError(
            f"pin file {PIN_PATH.name} does not pin: {', '.join(missing_from_pin)}")
    problems: list[str] = []
    for rel, expected in files.items():
        path = SOURCE_DIR / rel
        if not path.is_file():
            problems.append(f"{rel}: file missing (expected sha256 {expected})")
            continue
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual.lower() != str(expected).lower():
            problems.append(f"{rel}: sha256 mismatch (expected {expected}, got {actual})")
    if problems:
        raise UpstreamTableError(
            "upstream sources differ from the pin in " + PIN_PATH.name + ": "
            + "; ".join(problems) + ". Restore the pinned files or update the pin.")


