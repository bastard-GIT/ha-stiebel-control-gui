def generate(model: str) -> dict:
    """Build the v2 Elster table for model. Verifies the pin first."""
    verify_pin()
    defines = _table_defines(model)
    pin = pin_info()
    active = list(preprocess_lines(_source_lines(TABLE_FILE), defines, {}, source=TABLE_FILE))

    type_names = _parse_types(active)
    rows = _parse_rows(active, type_names)
    error_list = _parse_index_names(_block(active, _ERROR_BLOCK_RE, TABLE_FILE, "ErrorList"), "ErrorList")
    betriebsart_list = _parse_index_names(
        _block(active, _BETRIEB_BLOCK_RE, TABLE_FILE, "BetriebsartList"), "BetriebsartList")
    members, own_can_id = _parse_can_members()
    signals, duplicates = _signals(rows)

    commit = pin["commit"]
    return {
        "format_version": _FORMAT_VERSION,
        "description": (
            f"Elster table generated from upstream bullitt186/ha-stiebel-control "
            f"({commit[:7]}) for model {model}"),
        "source": {
            "repo": pin["repo"],
            "commit": commit,
            "date": pin["date"],
            "model": model,
            "license": _LICENSE,
            "copyright": list(_COPYRIGHT),
            "note": _NOTE,
            "duplicates_dropped": duplicates,
        },
        "types": [
            {"id": i, "name": name, "writable": _DEFAULT_WRITABLE.get(name, False)}
            for i, name in enumerate(type_names)
        ],
        "can_members": members,
        "frame_format": {"bus": {"own_can_id": own_can_id}},
        "signals": signals,
        "error_list": error_list,
        "betriebsart_list": betriebsart_list,
    }


def write_table(model: str, path: str | Path, indent: int = 1) -> Path:
    """Write generate(model) as UTF-8 JSON (ensure_ascii=False) and return the path."""
    return save_table(generate(model), path, indent)


def save_table(data: dict, path: str | Path, indent: int = 1) -> Path:
    """Write an already generated table dict as UTF-8 JSON and return the path."""
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=indent)
        fh.write("\n")
    return out
