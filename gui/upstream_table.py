_TOKEN_RE = re.compile(
    r"\s*(?:(?P<num>0[xX][0-9a-fA-F]+|\d+)|(?P<id>[A-Za-z_]\w*)|(?P<op>&&|\|\||==|!=|[!()]))")
_DIRECTIVE_RE = re.compile(r"#\s*(\w+)\s*(.*)$")
_FUNCTION_DEFINE_RE = re.compile(r"(\w+)(\([^)]*\))?(?:\s+(.*))?$")
_INT_LITERAL_RE = re.compile(r"0[xX][0-9a-fA-F]+|\d+")
_IDENT_RE = re.compile(r"\w+")


def _tokenize(expr: str) -> list[tuple[str, object]]:
    tokens: list[tuple[str, object]] = []
    pos = 0
    while True:
        match = _TOKEN_RE.match(expr, pos)
        if match is None:
            rest = expr[pos:].strip()
            if not rest:
                break
            raise UpstreamTableError(f"unsupported token in #if expression: {rest!r}")
        pos = match.end()
        if match.group("num") is not None:
            tokens.append(("num", _int(match.group("num"))))
        elif match.group("id") is not None:
            tokens.append(("id", match.group("id")))
        else:
            tokens.append(("op", match.group("op")))
    return tokens


class _ExpressionParser:
    """Recursive descent parser: || < && < (== !=) < ! < primary."""

    def __init__(self, tokens: list[tuple[str, object]], defines: set[str], values: dict[str, int]):
        self.tokens = tokens
        self.pos = 0
        self.defines = defines
        self.values = values

    def _peek(self) -> tuple[str, object] | None:
        return self.tokens[self.pos] if self.pos < len(self.tokens) else None

    def _next(self) -> tuple[str, object]:
        tok = self._peek()
        if tok is None:
            raise UpstreamTableError("unexpected end of #if expression")
        self.pos += 1
        return tok

    def _accept(self, kind: str, value: object) -> bool:
        tok = self._peek()
        if tok is not None and tok == (kind, value):
            self.pos += 1
            return True
        return False

    def parse(self) -> int:
        value = self.parse_or()
        if self.pos != len(self.tokens):
            raise UpstreamTableError(f"unexpected token {self._peek()[1]!r} in #if expression")
        return value

    def parse_or(self) -> int:
        value = self.parse_and()
        while self._accept("op", "||"):
            right = self.parse_and()
            value = 1 if (value or right) else 0
        return value

    def parse_and(self) -> int:
        value = self.parse_equality()
        while self._accept("op", "&&"):
            right = self.parse_equality()
            value = 1 if (value and right) else 0
        return value

    def parse_equality(self) -> int:
        left = self.parse_unary()
        while True:
            if self._accept("op", "=="):
                left = int(left == self.parse_unary())
            elif self._accept("op", "!="):
                left = int(left != self.parse_unary())
            else:
                return left

    def parse_unary(self) -> int:
        if self._accept("op", "!"):
            return int(not self.parse_unary())
        return self.parse_primary()

    def parse_primary(self) -> int:
        kind, value = self._next()
        if kind == "num":
            return int(value)  # type: ignore[arg-type]
        if kind == "op" and value == "(":
            inner = self.parse_or()
            if not self._accept("op", ")"):
                raise UpstreamTableError("missing ')' in #if expression")
            return inner
        if kind == "id":
            if value == "defined":
                return self._parse_defined()
            name = str(value)
            if name in self.values:
                return self.values[name]
            if name in self.defines:
                raise UpstreamTableError(
                    f"macro {name} has no integer value; use defined({name}) in #if expressions")
            raise UpstreamTableError(f"unknown identifier {name!r} in #if expression")
        raise UpstreamTableError(f"unexpected token {value!r} in #if expression")

    def _parse_defined(self) -> int:
        parenthesized = self._accept("op", "(")
        kind, name = self._next()
        if kind != "id":
            raise UpstreamTableError("defined must be followed by a macro name")
        if parenthesized and not self._accept("op", ")"):
            raise UpstreamTableError("missing ')' after defined(...)")
        return 1 if (str(name) in self.defines or str(name) in self.values) else 0


def evaluate_condition(expr: str, defines: set[str], values: dict[str, int]) -> bool:
    """Evaluate a #if expression. Unsupported syntax or unknown identifiers raise UpstreamTableError."""
    tokens = _tokenize(expr)
    if not tokens:
        raise UpstreamTableError("empty #if expression")
    return _ExpressionParser(tokens, defines, values).parse() != 0


@dataclass
class _Frame:
    lineno: int
    parent_active: bool
    taken: bool
    active: bool
    else_seen: bool = False


def _error(source: str, lineno: int, message: str) -> UpstreamTableError:
    return UpstreamTableError(f"{source}:{lineno}: {message}")


def _apply_define(rest: str, defines: set[str], values: dict[str, int], source: str, lineno: int) -> None:
    match = _FUNCTION_DEFINE_RE.match(rest)
    if match is None:
        raise _error(source, lineno, f"malformed #define {rest!r}")
    macro, params, body = match.group(1), match.group(2), (match.group(3) or "").strip()
    if params is not None:
        return  # function-like macros are never needed as values
    defines.add(macro)
    if _INT_LITERAL_RE.fullmatch(body):
        values[macro] = _int(body)
    # Any other body: the name counts as defined, but it has no integer value.


def _apply_undef(rest: str, defines: set[str], values: dict[str, int], source: str, lineno: int) -> None:
    match = _IDENT_RE.match(rest)
    if match is None:
        raise _error(source, lineno, f"malformed #undef {rest!r}")
    defines.discard(match.group(0))
    values.pop(match.group(0), None)


def preprocess_lines(
    lines: list[str],
    defines: set[str],
    values: dict[str, int] | None = None,
    *,
    apply_defines: bool = False,
    source: str = "<input>",
) -> Iterator[tuple[int, str]]:
    """Yield (line number, line) for every active line.

    lines must be comment-free (see strip_comments). defines and values are the macros
    known before the file starts. With apply_defines=True, #define and #undef update them
    in place; otherwise they are left alone and such lines are yielded like any other
    directive line (starting with '#') so that callers can reject them where they matter.
    Unknown directives raise only in active code, as a C compiler would not evaluate them
    in skipped code.
    """
    if values is None:
        values = {}
    stack: list[_Frame] = []
    index = 0
    total = len(lines)
    while index < total:
        lineno = index + 1
        raw = lines[index]
        index += 1
        text = raw.strip()
        active = stack[-1].active if stack else True

        if not text.startswith("#"):
            if active:
                yield lineno, raw
            continue

        while text.endswith("\\") and index < total:
            text = text[:-1].rstrip() + " " + lines[index].strip()
            index += 1
        match = _DIRECTIVE_RE.match(text)
        if match is None:
            raise _error(source, lineno, f"malformed directive {text!r}")
        name, rest = match.group(1), match.group(2).strip()

        if name in ("if", "ifdef", "ifndef"):
            if not active:
                stack.append(_Frame(lineno, False, True, False))
                continue
            if name == "if":
                cond = _eval_at(rest, defines, values, source, lineno)
            else:
                ident = _IDENT_RE.fullmatch(rest)
                if ident is None:
                    raise _error(source, lineno, f"#{name} needs one macro name, got {rest!r}")
                is_defined = rest in defines or rest in values
                cond = is_defined if name == "ifdef" else not is_defined
            stack.append(_Frame(lineno, True, cond, cond))
        elif name == "elif":
            if not stack:
                raise _error(source, lineno, "#elif without #if")
            frame = stack[-1]
            if frame.else_seen:
                raise _error(source, lineno, "#elif after #else")
            if frame.taken or not frame.parent_active:
                frame.active = False  # not evaluated: an earlier branch was taken
            else:
                cond = _eval_at(rest, defines, values, source, lineno)
                frame.taken = cond
                frame.active = cond
        elif name == "else":
            if not stack:
                raise _error(source, lineno, "#else without #if")
            frame = stack[-1]
            if frame.else_seen:
                raise _error(source, lineno, "second #else")
            frame.else_seen = True
            frame.active = frame.parent_active and not frame.taken
            frame.taken = True
        elif name == "endif":
            if not stack:
                raise _error(source, lineno, "#endif without #if")
            stack.pop()
        elif name in ("define", "undef"):
            if active and apply_defines:
                if name == "define":
                    _apply_define(rest, defines, values, source, lineno)
                else:
                    _apply_undef(rest, defines, values, source, lineno)
            elif active:
                yield lineno, text
        elif name in ("include", "pragma", "error"):
            if active:
                yield lineno, text
        elif active:
            raise _error(source, lineno, f"unsupported directive #{name}")

    if stack:
        raise _error(source, stack[-1].lineno, "#if without #endif at end of file")


def _eval_at(expr: str, defines: set[str], values: dict[str, int], source: str, lineno: int) -> bool:
    try:
        return evaluate_condition(expr, defines, values)
    except UpstreamTableError as exc:
        raise _error(source, lineno, str(exc)) from exc


