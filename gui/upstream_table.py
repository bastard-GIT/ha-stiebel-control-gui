def _block(active: list[tuple[int, str]], marker: re.Pattern, source: str, what: str) -> list[tuple[int, str]]:
    """Lines between the single active definition matching marker and its closing '};'."""
    starts = [i for i, (_, text) in enumerate(active) if marker.search(text)]
    if len(starts) != 1:
        raise UpstreamTableError(
            f"{source}: expected exactly one active definition of {what}, found {len(starts)}")
    body: list[tuple[int, str]] = []
    for lineno, text in active[starts[0] + 1:]:
        if text.strip() == "};":
            return body
        body.append((lineno, text))
    raise UpstreamTableError(f"{source}: {what} is not closed by '}};'")


_TYPE_BLOCK_RE = re.compile(r"\bElsterTypeStr\[\]\s*=")
_TABLE_BLOCK_RE = re.compile(r"\bElsterTable\[\]\s*=")
_ERROR_BLOCK_RE = re.compile(r"\bErrorList\[\]\s*=")
_BETRIEB_BLOCK_RE = re.compile(r"\bBetriebsartList\[\]\s*=")
_TYPE_STR_RE = re.compile(r'^"(\w+)"\s*,?$')
_ROW_RE = re.compile(
    r'^\{\s*"(?P<name>[^"]*)"\s*,\s*(?P<index>0[xX][0-9a-fA-F]+|\d+)\s*,\s*'
    r'(?P<type>et_\w+|0)\s*,\s*(?P<blacklisted>true|false)\s*,\s*(?P<metadata>true|false)\s*\}\s*,?$')
_INDEX_NAME_RE = re.compile(r'^\{\s*(?P<index>0[xX][0-9a-fA-F]+)\s*,\s*"(?P<name>[^"]*)"\s*\}\s*,?$')


@dataclass(frozen=True)
class _Row:
    lineno: int
    name: str
    index: int
    type: str


def _parse_types(active: list[tuple[int, str]]) -> list[str]:
    names: list[str] = []
    for lineno, text in _block(active, _TYPE_BLOCK_RE, TABLE_FILE, "ElsterTypeStr"):
        line = text.strip()
        if not line or line == "{":
            continue
        match = _TYPE_STR_RE.match(line)
        if match is None:
            raise _error(TABLE_FILE, lineno, f"unexpected line in ElsterTypeStr: {line!r}")
        names.append(match.group(1))
    if not names:
        raise UpstreamTableError(f"{TABLE_FILE}: ElsterTypeStr is empty")
    return names


def _parse_rows(active: list[tuple[int, str]], type_names: list[str]) -> list[_Row]:
    rows: list[_Row] = []
    for lineno, text in _block(active, _TABLE_BLOCK_RE, TABLE_FILE, "ElsterTable"):
        line = text.strip()
        if not line or line == "{":
            continue
        if line.startswith("#"):
            raise _error(TABLE_FILE, lineno, f"directive inside the ElsterTable body is not supported: {line!r}")
        match = _ROW_RE.match(line)
        if match is None:
            raise _error(TABLE_FILE, lineno, f"unrecognised ElsterTable row: {line!r}")
        index = _int(match.group("index"))
        if index > 0xFFFF:
            raise _error(TABLE_FILE, lineno, f"index out of range: {match.group('index')}")
        type_name = "et_default" if match.group("type") == "0" else match.group("type")
        if type_name not in type_names:
            raise _error(TABLE_FILE, lineno, f"type {type_name!r} is not in ElsterTypeStr")
        rows.append(_Row(lineno, match.group("name"), index, type_name))
    if not rows:
        raise UpstreamTableError(f"{TABLE_FILE}: ElsterTable has no rows")
    return rows


def _parse_index_names(body: list[tuple[int, str]], source: str) -> list[dict]:
    entries: list[dict] = []
    for lineno, text in body:
        line = text.strip()
        if not line or line == "{":
            continue
        match = _INDEX_NAME_RE.match(line)
        if match is None:
            raise _error(TABLE_FILE, lineno, f"unrecognised {source} entry: {line!r}")
        entries.append({"index": f"0x{_int(match.group('index')):04x}", "name": match.group("name")})
    return entries


def _signals(rows: list[_Row]) -> tuple[list[dict], list[dict]]:
    """Apply the upstream duplicate rule: the first row with an index wins."""
    kept: dict[int, _Row] = {}
    signals: list[dict] = []
    duplicates: list[dict] = []
    for row in rows:
        if row.index in kept:
            duplicates.append({
                "index": f"0x{row.index:04x}",
                "kept": kept[row.index].name,
                "dropped": row.name,
            })
            continue
        kept[row.index] = row
        signal = {
            "name": row.name,
            "index": f"0x{row.index:04x}",
            "index_int": row.index,
            "type": row.type,
            "owner": None,
            "owner_name": None,
            "poll": None,
        }
        if row.name == _SENTINEL and row.index == 0:
            signal["sentinel"] = True
        signals.append(signal)
    if not signals or not signals[0].get("sentinel"):
        raise UpstreamTableError(f"{TABLE_FILE}: {_SENTINEL} 0x0000 must be the first row")
    return signals, duplicates


