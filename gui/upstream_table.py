_MODEL_ID_RE = re.compile(r"#\s*define\s+HA_MODEL_ID_(\w+)\s+(\d+)\s*$")


def _model_ids() -> dict[str, int]:
    """All HA_MODEL_ID_<name> numbers of model_profile.h in file order (incl. test_model, unknown)."""
    ids: dict[str, int] = {}
    for line in _source_lines(PROFILE_FILE):
        match = _MODEL_ID_RE.match(line.strip())
        if match is None:
            continue
        name = match.group(1)
        if name in ids:
            raise UpstreamTableError(f"{PROFILE_FILE}: HA_MODEL_ID_{name} defined twice")
        ids[name] = int(match.group(2))
    if not ids:
        raise UpstreamTableError(f"{PROFILE_FILE}: no HA_MODEL_ID_* numbers found")
    return ids


def available_models() -> list[str]:
    """Model names of model_profile.h (HA_MODEL_ID_* without test_model and unknown)."""
    return [name for name in _model_ids() if name not in _NON_MODELS]


def _check_model(model: str) -> None:
    models = available_models()
    if model not in models:
        raise UpstreamTableError(
            f"unknown model {model!r}; known models: {', '.join(models)}")


def defines_for(model: str) -> set[str]:
    """Which of MODEL_DEFINES are defined for model, evaluated from model_profile.h.

    The header derives HA_MODEL_ID from HA_DEVICE_MODEL by token pasting; here HA_MODEL_ID is
    set to the number of the requested model, and the header's line is checked to be exactly
    that derivation.
    """
    _check_model(model)
    ids = _model_ids()
    lines = _source_lines(PROFILE_FILE)
    if sum(1 for line in lines if line.strip() == _MODEL_ID_MACRO_LINE) != 1:
        raise UpstreamTableError(
            f"{PROFILE_FILE}: expected exactly one line '{_MODEL_ID_MACRO_LINE}'")
    defines: set[str] = {"__cplusplus"}
    values = {f"HA_MODEL_ID_{name}": number for name, number in ids.items()}
    values["HA_MODEL_ID"] = ids[model]
    # Consume the generator completely: it updates defines and values in place.
    list(preprocess_lines(lines, defines, values, apply_defines=True, source=PROFILE_FILE))
    return {name for name in MODEL_DEFINES if name in defines}


def _table_defines(model: str) -> set[str]:
    return defines_for(model) | {"ELSTER_TABLE_DEFINITIONS"}


