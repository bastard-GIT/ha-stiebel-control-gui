_MEMBERS_BLOCK_RE = re.compile(r"\bCanMembers\[\]\s*=")
_MEMBER_RE = re.compile(r'\{\s*"([^"]+)"\s*,\s*(0[xX][0-9a-fA-F]+|\d+)\s*\}')


def _parse_can_members() -> tuple[list[dict], str]:
    """Return (members, own CAN ID as '0x%03x') from CanMembers[] of can_members.h."""
    lines = _source_lines(MEMBERS_FILE)
    starts = [i for i, line in enumerate(lines) if _MEMBERS_BLOCK_RE.search(line)]
    if len(starts) != 1:
        raise UpstreamTableError(f"{MEMBERS_FILE}: expected exactly one CanMembers[] definition")
    text = "\n".join(lines[starts[0]:])
    end = text.find("};")
    if end < 0:
        raise UpstreamTableError(MEMBERS_FILE + ": CanMembers[] is not closed by '};'")
    body = text[:end].split("=", 1)[1]
    pairs = _MEMBER_RE.findall(body)
    if body.count("{") != len(pairs) + 1:  # +1 for the array brace
        raise UpstreamTableError(f"{MEMBERS_FILE}: unrecognised entry in CanMembers[]")
    members: list[dict] = []
    for name, can_text in pairs:
        can_id = _int(can_text)
        if can_id > 0x7FF:
            raise UpstreamTableError(f"{MEMBERS_FILE}: CAN ID out of range for {name}")
        # Rule of generate_read_id / generate_write_id in can_io.h (lines 65 and 71).
        address = ((can_id & 0x780) // 8) & 0xFF
        members.append({
            "name": name,
            "enum_name": "cm_" + name.lower(),
            "can_id": f"0x{can_id:03x}",
            "read_id": [f"0x{((address & 0xF0) + 1) & 0xFF:02x}", f"0x{can_id & 0x7F:02x}"],
            "write_id": [f"0x{address & 0xF0:02x}", f"0x{can_id & 0x7F:02x}"],
        })
    own = [m for m in members if m["name"] == _OWN_MEMBER]
    if len(own) != 1:
        raise UpstreamTableError(f"{MEMBERS_FILE}: member {_OWN_MEMBER} not found exactly once")
    return members, own[0]["can_id"]


